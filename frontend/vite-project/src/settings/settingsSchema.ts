export type SettingScope = "application" | "user" | "workspace" | "folder" | "language"
export type SettingStatus = "ready" | "planned" | "requires-vscode-service"
export type SettingControl =
  | "text"
  | "password"
  | "number"
  | "boolean"
  | "select"
  | "textarea"
  | "json"
  | "button"

export interface SettingOption {
  label: string
  value: string | number | boolean
}

export interface SettingDefinition<T = unknown> {
  key: string
  vscodeKey?: string
  title: string
  description: string
  group: string
  scope: SettingScope[]
  control: SettingControl
  defaultValue: T
  options?: SettingOption[]
  status?: SettingStatus
}

