export function getSettingDefinition(key: string): SettingDefinition | undefined {
  return SETTINGS_SCHEMA.find((setting) => setting.key === key || setting.vscodeKey === key)
}

export function getSettingsByGroup(group: string): SettingDefinition[] {
  return SETTINGS_SCHEMA.filter((setting) => setting.group === group)
}

export function getDefaultSettings(): Record<string, unknown> {
  return Object.fromEntries(SETTINGS_SCHEMA.map((setting) => [setting.key, setting.defaultValue]))
}
